#!/usr/bin/env bash
# Writes the texts built into the binary: Sources/GzymsCore/Skill.gen.swift from skill/*.md (what `gzyms skill` prints)
# and Sources/GzymsCore/WhatsNew.gen.swift from whatsnew/<version>.md (the notes shown once after an update).
# Run after editing either folder (check.sh and install-dev.sh run it too).
set -euo pipefail
cd "$(dirname "$0")/.."

# gen <dir> <out file> <swift name>
gen() {
  {
    echo "// Generated by scripts/gen-skill.sh from $1/*.md. Do not edit by hand: edit the .md and run the script."
    echo
    echo '/// File name without .md, then its text.'
    echo "let $3: [String: String] = ["
    for f in "$1"/*.md; do
      printf '    "%s": ##"""\n' "$(basename "$f" .md)"
      cat "$f"
      echo  # the closing quotes drop one newline, this keeps the file's own
      echo '"""##,'
    done
    echo ']'
  } >"$2"
}
gen skill Sources/GzymsCore/Skill.gen.swift skillFiles
gen whatsnew Sources/GzymsCore/WhatsNew.gen.swift whatsNewFiles
